// 功能：读入 n，创建长度为 n 的数组并填入 1~n，最后逐个打印

int main() // main 函数：程序的入口，操作系统从这里开始执行
{
	int i = 0; // 循环计数器，下面两个 for 循环共用
	int n = 0; // 数组长度，由用户输入决定
	printf("请输入数组长度："); // 打印提示语（结尾不加 \n，光标会停在冒号后面等你输入）
	scanf("%d", &n); // 从键盘读取一个整数存入 n；& 取地址，scanf 必须通过地址才能写入
	int arr[n]; // 变长数组 VLA（C99 特性）：长度由变量 n 决定；GCC 支持，但 MSVC 不支持

	for (i = 0; i < n; i++) // 第一个循环：给数组的每个元素赋值
	{
		arr[i] = i + 1; // arr[0]=1、arr[1]=2 …… arr[n-1]=n
	}
	for (i = 0; i < n; i++) // 第二个循环：遍历数组并打印
	{
		printf("%d ", arr[i]); // 每个元素后面跟一个空格，所以输出形如 1 2 3 4 5
	}

	return 0; // 返回 0 给操作系统，表示程序正常结束（非 0 一般表示出错）
}
